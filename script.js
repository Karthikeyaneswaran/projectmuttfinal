// 9. Live Mutt Hours Status Check
function checkLiveStatus() {
    const indicator = document.getElementById('live-indicator');
    const statusText = document.getElementById('live-status-text');
    if (!indicator || !statusText) return;

    const today = new Date();
    const currentHour = today.getHours();
    const currentMinute = today.getMinutes();

    // Opening timings: 06:00 AM (6:00) to 06:30 PM (18:30)
    const currentTotalMinutes = currentHour * 60 + currentMinute;
    const openMinutes = 6 * 60; // 06:00 AM
    const closeMinutes = 18 * 60 + 30; // 06:30 PM

    if (currentTotalMinutes >= openMinutes && currentTotalMinutes <= closeMinutes) {
        indicator.className = 'status-indicator live';
        statusText.textContent = translations[currentLang].pooja_live_open;
    } else {
        indicator.className = 'status-indicator closed';
        // Add a closed styling override temporarily
        indicator.style.backgroundColor = 'rgba(165, 42, 42, 0.1)';
        indicator.style.color = 'var(--primary)';
        const dot = indicator.querySelector('.dot');
        if (dot) dot.style.backgroundColor = 'var(--primary)';
        statusText.textContent = translations[currentLang].pooja_live_closed;
    }
}

