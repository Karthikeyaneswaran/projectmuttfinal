function initGalleryLightbox() {
    const lightbox = document.getElementById('gallery-lightbox');
    const lightboxImg = document.getElementById('lightbox-img');
    const lightboxTitle = document.getElementById('lightbox-title');
    const lightboxDesc = document.getElementById('lightbox-desc');
    const lightboxCurrent = document.getElementById('lightbox-current');
    const lightboxTotal = document.getElementById('lightbox-total');
    const closeBtn = document.querySelector('.lightbox-close');
    const prevBtn = document.querySelector('.lightbox-prev');
    const nextBtn = document.querySelector('.lightbox-next');

    if (!lightbox) return;

    // Attach click listener to gallery items
    const galleryItems = document.querySelectorAll('.gallery-item');
    galleryItems.forEach(item => {
        item.addEventListener('click', () => {
            const galleryId = item.getAttribute('data-gallery-id');
            if (gallerySlides[galleryId]) {
                currentSlides = gallerySlides[galleryId];
                currentSlideIndex = 0;
                openLightbox();
            }
        });
    });

    function openLightbox() {
        lightbox.classList.add('open');
        lightbox.setAttribute('aria-hidden', 'false');
        document.body.style.overflow = 'hidden'; // Disable page scrolling
        showSlide(currentSlideIndex);
    }

    function closeLightbox() {
        lightbox.classList.remove('open');
        lightbox.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = ''; // Enable page scrolling
        lightboxImg.src = '';
    }

    function showSlide(index) {
        if (index < 0) index = currentSlides.length - 1;
        if (index >= currentSlides.length) index = 0;
        currentSlideIndex = index;

        const slide = currentSlides[currentSlideIndex];
        
        // Smooth image swap transition
        lightboxImg.style.opacity = '0';
        setTimeout(() => {
            lightboxImg.src = slide.img;
            lightboxImg.alt = translations[currentLang][slide.titleKey] || '';
            lightboxImg.style.opacity = '1';
        }, 150);

        // Update translated texts dynamically
        lightboxTitle.setAttribute('data-translate', slide.titleKey);
        lightboxTitle.textContent = translations[currentLang][slide.titleKey] || '';

        lightboxDesc.setAttribute('data-translate', slide.descKey);
        lightboxDesc.textContent = translations[currentLang][slide.descKey] || '';

        // Update slide numbers
        lightboxCurrent.textContent = currentSlideIndex + 1;
        lightboxTotal.textContent = currentSlides.length;

        // Hide navigation arrows if there's only one slide
        if (currentSlides.length <= 1) {
            prevBtn.style.display = 'none';
            nextBtn.style.display = 'none';
        } else {
            prevBtn.style.display = 'flex';
            nextBtn.style.display = 'flex';
        }
    }

    // Event listeners for closing
    closeBtn.addEventListener('click', closeLightbox);
    lightbox.addEventListener('click', (e) => {
        // If clicking background overlay (not inside content container)
        if (e.target === lightbox) {
            closeLightbox();
        }
    });

    // Navigation buttons
    prevBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        showSlide(currentSlideIndex - 1);
    });

    nextBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        showSlide(currentSlideIndex + 1);
    });

    // Keyboard navigation
    document.addEventListener('keydown', (e) => {
        if (!lightbox.classList.contains('open')) return;
        
        if (e.key === 'Escape') {
            closeLightbox();
        } else if (e.key === 'ArrowLeft') {
            showSlide(currentSlideIndex - 1);
        } else if (e.key === 'ArrowRight') {
            showSlide(currentSlideIndex + 1);
        }
    });
}

